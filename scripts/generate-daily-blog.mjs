// Helper: Read all existing posts and their metadata
function getExistingPosts() {
  if (!fs.existsSync(BLOGS_DIR)) return [];
  const files = fs.readdirSync(BLOGS_DIR).filter((f) => f.endsWith(".md") || f.endsWith(".mdx"));
  
  return files.map((fileName) => {
    const slug = fileName.replace(/\.mdx?$/, "");
    const fullPath = path.join(BLOGS_DIR, fileName);
    const content = fs.readFileSync(fullPath, "utf8");
    const titleMatch = content.match(/title:\s*["']?([^"'\n\r]+)["']?/i);
    const title = titleMatch ? titleMatch[1].trim() : slug;
    return { slug, title, fileName };
  });
}

// Tokenize text into keywords to compute similarity
function extractKeywords(text) {
  const stopWords = new Set([
    "how", "the", "and", "for", "with", "using", "your", "what", "from", "into", "that", "this",
    "are", "why", "who", "all", "its", "can", "our", "their", "when", "where", "which"
  ]);
  return text
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, " ")
    .split(/\s+/)
    .filter((w) => w.length > 3 && !stopWords.has(w));
}

// Check if a candidate seed has too much keyword overlap with existing articles
function isTopicAlreadyCovered(seed, existingPosts) {
  const seedKeywords = new Set(extractKeywords(seed));
  if (seedKeywords.size === 0) return false;

  for (const post of existingPosts) {
    const postKeywords = extractKeywords(`${post.slug} ${post.title}`);
    let overlapCount = 0;
    for (const kw of postKeywords) {
      if (seedKeywords.has(kw)) overlapCount++;
    }
    const overlapRatio = overlapCount / seedKeywords.size;
    // If over 60% of significant keywords overlap with an existing article, consider it duplicate
    if (overlapRatio >= 0.6) {
      return true;
    }
  }
  return false;
}

