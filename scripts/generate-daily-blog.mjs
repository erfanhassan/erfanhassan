function extractSlug(content, existingSlugs) {
  let slug = "";
  const match = content.match(/slug:\s*["']?([^"'\n\r]+)["']?/i);
  if (match && match[1]) {
    slug = match[1].trim();
  } else {
    // Fallback to title
    const titleMatch = content.match(/title:\s*["']?([^"'\n\r]+)["']?/i);
    if (titleMatch && titleMatch[1]) {
      slug = titleMatch[1]
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-|-$/g, "");
    } else {
      slug = `ai-article-${Date.now()}`;
    }
  }

  // Ensure slug collision guard
  if (existingSlugs.includes(slug)) {
    const today = new Date().toISOString().split("T")[0];
    slug = `${slug}-${today}`;
  }

  return slug;
}

// ── IndexNow Ping for Instant Search Engine & AI Crawler Discovery ────────
async function pingIndexNow(slug) {
  const siteUrl = process.env.NEXT_PUBLIC_SITE_URL || "https://erfanhassan.sonictch.com";
  const articleUrl = `${siteUrl}/blog/${slug}`;
  const indexNowKey = process.env.INDEXNOW_KEY;

  if (!indexNowKey) {
    console.log("ℹ️ IndexNow ping skipped (INDEXNOW_KEY not configured in env).");
    return;
  }

  try {
    const host = new URL(siteUrl).host;
    console.log(`📡 Pinging IndexNow for: ${articleUrl}...`);
    const res = await fetch("https://api.indexnow.org/indexnow", {
      method: "POST",
      headers: { "Content-Type": "application/json; charset=utf-8" },
      body: JSON.stringify({
        host,
        key: indexNowKey,
        keyLocation: `${siteUrl}/${indexNowKey}.txt`,
        urlList: [articleUrl, `${siteUrl}/sitemap.xml`, `${siteUrl}/blog`],
      }),
    });
    console.log(`📡 IndexNow response status: ${res.status}`);
  } catch (err) {
    console.warn("⚠️ IndexNow ping failed non-fatally:", err.message);
  }
}

